  const pageIcon =
    '<path d="M13 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V9zM13 2v7h7"/>';

  const domainIcon =
    '<circle cx="12" cy="12" r="10"/><path d="M2 12h20M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z"/>';

  const evidenceIcons = {
    warning: svg(
      '<path d="M12 9v4M12 17h.01M10.29 3.86L1.82 18a2 2 0 0 0 1.71 3h16.94a2 2 0 0 0 1.71-3L13.71 3.86a2 2 0 0 0-3.42 0z"/>',
    ),
    shield: svg(
      '<path d="M12 22s8-4 8-10V5l-8-3-8 3v7c0 6 8 10 8 10zM12 8v5M12 16h.01"/>',
    ),
  };

  const settingKeys = [
    'enableAutoScan',
    'autoScan',
    'ignoreRules',
    'adBlockDisabledDomains',
    'cosmeticDisabledDomains',
    'selectedMode',
    'activeMode',
  ];

  const state = {
    tab: null,
    page: null,
    settings: {},
    pendingScan: null,
    busy: false,
    minimumTimestamp: 0,
    revision: 0,
    disposed: false,
    reputationTarget: null,
    reputationOpening: false,
  };

  let refreshTimer = null;
  let scanTimer = null;

  const version = chrome.runtime.getManifest().version;
  byId('version').textContent = `v${version}`;
  byId('version-display').textContent = `Dadblock v${version}`;

  const asArray = (value) =>
    Array.isArray(value) ? value : [];

  const readable = (value) =>
    typeof value === 'string'
      ? value.trim().slice(0, 400)
      : '';

  function artifactText(value, limit = 240) {
    if (typeof value !== 'string') return '';

    return value
      .replace(/[\u0000-\u001f\u007f]+/g, ' ')
      .replace(
        /[\u200b-\u200f\u202a-\u202e\u2060-\u2069\ufeff]/g,
        '',
      )
      .replace(/\s+/g, ' ')
      .trim()
      .replace(
        /^(?:[-*•]\s+|\d+[.)]\s+)/,
        '',
      )
      .slice(0, limit);
  }

  function selectedMode(settings) {
    const mode =
      settings.selectedMode ||
      settings.activeMode;

    return mode === 'local' ? 'local' : 'cloud';
  }

  function autoScanEnabled(settings) {
    return typeof settings.enableAutoScan === 'boolean'
      ? settings.enableAutoScan
      : settings.autoScan !== false;
  }

  function requestedModeFor(result) {
    if (
      result.requestedMode === 'local' ||
      result.requestedMode === 'cloud'
    ) {
      return result.requestedMode;
    }

    // Compatibility with an earlier background result.
    // fallbackFrom is generated by Dadblock's fallback handler.
    if (
      result.mode === 'local' &&
      [
        'ERROR',
        'RATE_LIMITED',
        'QUOTA_EXCEEDED',
      ].includes(result.fallbackFrom)
    ) {
      return 'cloud';
    }

    return (
      result.mode === 'local' ||
      result.mode === 'cloud'
    )
      ? result.mode
      : null;
  }

  function resultMatchesMode(result, mode) {
    const requested =
      requestedModeFor(result);

    return requested
      ? requested === mode
      : result.conclusive !== true;
  }

  function clearResultSource() {
    if (!ui.source) return;

    ui.source.hidden = true;
    ui.source.textContent = '';
  }

  function renderResultSource(result) {
    clearResultSource();

    if (
      !ui.source ||
      result.schemaVersion !== 2
    ) {
      return;
    }

    if (
      result.conclusive !== true &&
      result.judgment !== 'INCONCLUSIVE'
    ) {
      return;
    }

    const engine =
      result.engineMode || result.mode;

    if (
      engine !== 'local' &&
      engine !== 'cloud'
    ) {
      return;
    }

    const requested =
      requestedModeFor(result);

    const fallback =
      requested === 'cloud' &&
      engine === 'local';

    const origin =
      engine === 'local'
        ? 'Local AI'
        : 'Cloud AI';

    const suffix =
      fallback
        ? ' · Cloud fallback'
        : (
            result.cached === true ||
            result.cacheHit === true
          )
          ? ' · cached result'
          : '';

    ui.source.textContent =
      'Result from ' + origin + suffix;

    ui.source.hidden = false;
  }

  function webPage(url) {
    try {
      const parsed = new URL(url);

      if (
        parsed.protocol !== 'https:' &&
        parsed.protocol !== 'http:'
      ) {
        return null;
      }

      if (
        parsed.hostname ===
        'chromewebstore.google.com'
      ) {
        return null;
      }

      if (
        parsed.hostname === 'chrome.google.com' &&
        /^\/webstore(?:\/|$)/.test(parsed.pathname)
      ) {
        return null;
      }

      return parsed;
    } catch {
      return null;
    }
  }

  function activeRule(rule) {
    return (
      rule &&
      typeof rule === 'object' &&
      typeof rule.pattern === 'string' &&
      !(rule.expiry && Date.now() > rule.expiry)
    );
  }

  function isIgnored(url, hostname, rules) {
    return asArray(rules).some((rule) => {
      if (!activeRule(rule)) return false;

      if (rule.type === 'url') {
        return rule.pattern === url;
      }

      if (
        rule.type === 'url_prefix' ||
        rule.type === 'url_temporary'
      ) {
        return url.startsWith(rule.pattern);
      }

      return (
        (
          rule.type === 'domain' ||
          rule.type === 'domain_temporary'
        ) &&
        rule.pattern === hostname
      );
    });
  }

  function clearEvidence() {
    ui.evidenceCard.hidden = true;
    ui.evidenceList.replaceChildren();
    ui.dadTipBox.hidden = true;
    ui.dadTipText.textContent = '';
  }

  function renderEvidence(result) {
    clearEvidence();

    if (ui.evidenceTitle) {
      ui.evidenceTitle.textContent =
        result.judgment === 'WARNING'
          ? 'Observed details'
          : 'Evidence & Artifacts';
    }

    if (!Array.isArray(result.evidence)) return;

    const points = [];
    const seen = new Set();

    for (
      const value of result.evidence.slice(0, 12)
    ) {
      const text = artifactText(value);
      const key = text.toLowerCase();

      if (!text || seen.has(key)) continue;

      seen.add(key);
      points.push(text);

      if (points.length === 3) break;
    }

    if (!points.length) return;

    const fragment =
      document.createDocumentFragment();

    const iconMarkup =
      result.judgment === 'WARNING'
        ? evidenceIcons.warning
        : evidenceIcons.shield;

    for (const point of points) {
      const item = document.createElement('li');
      const icon = document.createElement('span');
      const label = document.createElement('span');

      icon.className = 'evidence-icon';
      icon.setAttribute('aria-hidden', 'true');
      icon.innerHTML = iconMarkup;

      // Page/model text is never interpreted as markup.
      label.textContent = point;

      item.append(icon, label);
      fragment.append(item);
    }

    ui.evidenceList.append(fragment);

    const tip = artifactText(result.dadTip, 320);

    if (tip) {
      ui.dadTipText.textContent = tip;
      ui.dadTipBox.hidden = false;
    }

    ui.evidenceCard.hidden = false;
  }

  function clearShopping() {
    state.reputationTarget = null;
    ui.shoppingCard.hidden = true;
    ui.shoppingDomain.textContent = '';
    ui.trustpilot.disabled = true;
    ui.reddit.disabled = true;
    ui.reputationStatus.hidden = true;
    ui.reputationStatus.textContent = '';
  }

  function reputationHostname(page) {
    if (!page) return '';

    // Preserve the exact hostname, including www/subdomains.
    // Do not guess a registrable domain.
    const hostname = page.hostname
      .toLowerCase()
      .replace(/\.$/, '');

    if (
      !hostname ||
      hostname.length > 253 ||
      !hostname.includes('.') ||
      !/^[a-z0-9.-]+$/.test(hostname) ||
      /^[\d.]+$/.test(hostname) ||
      hostname.endsWith('.localhost') ||
      hostname.endsWith('.local')
    ) {
      return '';
    }

    const labels = hostname.split('.');

    if (
      labels.some((label) =>
        !label ||
        label.length > 63 ||
        !/^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/.test(label)
      )
    ) {
      return '';
    }

    return hostname;
  }

  function renderShopping(result) {
    clearShopping();

    if (
      result.isStorefront !== true ||
      !state.page ||
      !Number.isInteger(state.tab?.id)
    ) {
      return;
    }

    const hostname =
      reputationHostname(state.page);

    if (!hostname) return;

    state.reputationTarget = {
      tabId: state.tab.id,
      windowId: state.tab.windowId,
      url: state.tab.url,
      hostname,
    };

    ui.shoppingDomain.textContent = hostname;

    ui.trustpilot.disabled =
      state.reputationOpening;

    ui.reddit.disabled =
      state.reputationOpening;

    ui.shoppingCard.hidden = false;
  }

  async function openReputationSearch(provider) {
    if (
      state.disposed ||
      state.reputationOpening ||
      !state.reputationTarget ||
      !['trustpilot', 'reddit'].includes(provider)
    ) {
      return;
    }

    const target =
      state.reputationTarget;

    state.reputationOpening = true;
    ui.trustpilot.disabled = true;
    ui.reddit.disabled = true;
    ui.reputationStatus.hidden = true;
    ui.reputationStatus.textContent = '';

    try {
      const [tab] = await chrome.tabs.query({
        active: true,
        currentWindow: true,
      });

      if (
        state.disposed ||
        state.reputationTarget !== target
      ) {
        return;
      }

      const page =
        tab ? webPage(tab.url) : null;

      // Never search for a previous page from a stale card.
      if (
        !tab ||
        tab.id !== target.tabId ||
        tab.windowId !== target.windowId ||
        tab.url !== target.url ||
        reputationHostname(page) !== target.hostname
      ) {
        clearShopping();
        scheduleRefresh();
        return;
      }

      const search = new URL(
        'https://www.google.com/search'
      );

      const query =
        provider === 'trustpilot'
          ? `"${target.hostname}" trustpilot`
          : `"${target.hostname}" site:reddit.com reviews`;

      search.searchParams.set('q', query);

      // Fixed trusted origin; no model-provided destination.
      const createOptions = {
        url: search.toString(),
        active: true,
      };

      if (Number.isInteger(tab.windowId)) {
        createOptions.windowId = tab.windowId;
      }

      if (Number.isInteger(tab.index)) {
        createOptions.index = tab.index + 1;
      }

      await chrome.tabs.create(createOptions);
    } catch {
      if (
        !state.disposed &&
        state.reputationTarget === target
      ) {
        ui.reputationStatus.textContent =
          'The search tab could not open. Please try again.';

        ui.reputationStatus.hidden = false;
      }
    } finally {
      state.reputationOpening = false;

      if (
        !state.disposed &&
        state.reputationTarget
      ) {
        ui.trustpilot.disabled = false;
        ui.reddit.disabled = false;
      }
    }
  }

  function setState(
    signal,
    title,
    description,
    scanning = false
  ) {
    ui.hero.className =
      signal === 'neutral'
        ? 'hero-section state-skipped state-neutral'
        : `hero-section state-${signal}`;

    ui.hero.dataset.signal = signal;
    ui.hero.setAttribute(
      'aria-busy',
      String(scanning)
    );

    ui.avatar.innerHTML = faces[signal];
    ui.title.textContent = title;
    ui.description.textContent = description;

    clearResultSource();

    ui.details.hidden = true;
    ui.details.classList.add('hidden');
    ui.actionText.textContent = '';
    ui.analysisText.textContent = '';

    clearEvidence();
    clearShopping();
  }

  function showScanning() {
    setState(
      'neutral',
      'Dad is checking this page...',
      'Waiting for a completed scan.',
      true,
    );
  }

  function displayResult(result) {
    const r =
      result &&
      typeof result === 'object' &&
      !Array.isArray(result)
        ? result
        : {};

    const validatedSafe =
      r.signal === 'safe' &&
      r.safe === true &&
      r.schemaVersion === 2 &&
      r.judgment === 'SAFE' &&
      r.conclusive === true &&
      r.isMalicious === false;

    if (validatedSafe) {
      setState(
        'safe',
        'No scam indicators found',
        'Dadblock found no scam indicators in the scanned page text.',
      );
    } else if (
      r.signal === 'danger' &&
      [
        'SCAM',
        'WARNING',
        'THREAT',
      ].includes(r.judgment)
    ) {
      const warning =
        r.judgment === 'WARNING';

      setState(
        warning ? 'warning' : 'danger',
        warning
          ? r.warningKind === 'streaming'
            ? 'Dad has a heads-up'
            : 'Dad recommends caution here.'
          : 'Possible scam detected.',
        warning
          ? r.warningKind === 'streaming'
            ? 'Nothing urgent, just worth knowing.'
            : 'Check the observed details before continuing.'
          : 'Read the evidence before sharing details or paying.',
      );

      ui.details.hidden = false;
      ui.details.classList.remove('hidden');

      ui.actionText.textContent =
        r.judgment === 'WARNING'
          ? 'What Dad noticed'
          : 'Why Dad flagged this page';

      ui.analysisText.textContent =
        readable(r.analysis) ||
        'Dadblock flagged potentially harmful content.';
    } else {
      const neutralTitles = {
        QUOTA_EXCEEDED:
          'Scan quota reached',
        RATE_LIMITED:
          'Scan temporarily limited',
        INCONCLUSIVE:
          'Page not verified',
        INBOX:
          'Open a message to scan',
        SKIPPED:
          'Page not scanned',
        IGNORED:
          'Scanning paused here',
        AI_UNAVAILABLE:
          'On-device scanner unavailable',
        CONFIGURATION_ERROR:
          'Scanner needs setup',
        ERROR:
          'Scan could not complete',
      };

      const timedOut =
        r.method === 'timeout' ||
        (
          typeof r.code === 'string' &&
          r.code.includes('TIMEOUT')
        );

      const title =
        timedOut
          ? 'Scan timed out'
          : r.code === 'AUTO_SCAN_DISABLED'
            ? 'Automatic scanning is off'
            : neutralTitles[r.judgment] ||
              'Page not verified';

      setState(
        'neutral',
        title,
        readable(r.analysis) ||
          'This page has not been verified. Use "Scan now" to check it.',
      );
    }

    // Storefront classification is independent of the safety verdict.
    renderEvidence(r);
    renderShopping(r);
    renderResultSource(r);
  }

  function updateControls() {
    const page = state.page;

    const rules =
      asArray(state.settings.ignoreRules);

    const locked =
      state.busy || !!state.pendingScan;

    const ignored =
      !!page &&
      isIgnored(
        state.tab.url,
        page.hostname,
        rules
      );

    const unavailable =
      !page ||
      state.tab?.status === 'loading';

    ui.scan.disabled =
      locked || unavailable || ignored;

    ui.rescan.disabled =
      ui.scan.disabled;

    ui.scan.textContent =
      state.pendingScan
        ? 'Scanning...'
        : 'Scan now';

    for (
      const button of [
        ui.ignoreUrl,
        ui.ignoreDomain,
        ui.repair,
      ]
    ) {
      button.disabled =
        locked || !page;
    }

    const urlIgnored =
      !!page &&
      rules.some((rule) =>
        activeRule(rule) &&
        rule.type === 'url' &&
        rule.pattern === state.tab.url
      );

    const domainIgnored =
      !!page &&
      rules.some((rule) =>
        activeRule(rule) &&
        rule.type === 'domain' &&
        rule.pattern === page.hostname
      );

    const cosmeticDisabled =
      !!page &&
      asArray(
        state.settings.cosmeticDisabledDomains
      ).includes(page.hostname);

    ui.ignoreUrl.innerHTML = svg(
      pageIcon +
      (
        urlIgnored
          ? '<path d="m9 15 2 2 4-4"/>'
          : '<path d="M9 15h6"/>'
      ),
    );

    ui.ignoreDomain.innerHTML = svg(
      domainIgnored
        ? '<circle cx="12" cy="12" r="10"/><path d="m8 12 3 3 5-6"/>'
        : domainIcon,
    );

    const labels = [
      [
        ui.ignoreUrl,
        urlIgnored,
        urlIgnored
          ? 'Resume scanning this page'
          : 'Ignore this page (scan only)',
      ],
      [
        ui.ignoreDomain,
        domainIgnored,
        domainIgnored
          ? 'Resume Dadblock on this site'
          : 'Pause Dadblock on this site',
      ],
      [
        ui.repair,
        cosmeticDisabled,
        cosmeticDisabled
          ? 'CSS ad hiding is disabled on this site'
          : 'Page looks broken: disable CSS ad hiding on this site',
      ],
    ];

    for (
      const [button, pressed, label]
      of labels
    ) {
      button.title = label;

      button.setAttribute(
        'aria-label',
        label
      );

      button.setAttribute(
        'aria-pressed',
        String(pressed)
      );

      button.classList.toggle(
        'active-toggle',
        pressed
      );
    }

    if (cosmeticDisabled) {
      ui.repair.disabled = true;
    }
  }

  function clearPendingScan() {
    clearTimeout(scanTimer);
    scanTimer = null;
    state.pendingScan = null;
  }

  function adoptTab(tab) {
    if (
      state.tab?.id !== tab?.id ||
      state.tab?.url !== tab?.url
    ) {
      clearPendingScan();
      clearEvidence();
      clearShopping();
      clearResultSource();

      if (
        state.tab?.id !== tab?.id
      ) {
        state.minimumTimestamp = 0;
      }
    }

    state.tab = tab || null;

    state.page =
      tab &&
      Number.isInteger(tab.id)
        ? webPage(tab.url)
        : null;
  }

  function request(
    message,
    timeoutMs = 10000
  ) {
    return new Promise(
      (resolve, reject) => {
        const timer = setTimeout(
          () => reject(
            new Error('Message timeout')
          ),
          timeoutMs,
        );

        Promise.resolve()
          .then(() =>
            chrome.runtime.sendMessage(
              message
            )
          )
          .then(
            response => {
              clearTimeout(timer);
              resolve(response);
            },
            error => {
              clearTimeout(timer);
              reject(error);
            },
          );
      }
    );
  }

  function scheduleRefresh() {
    if (state.disposed) return;

    state.revision++;
    clearTimeout(refreshTimer);

    refreshTimer = setTimeout(
      () => {
        refreshTimer = null;
        void refreshStatus();
      },
      40
    );
  }

  async function refreshStatus() {
    const revision =
      ++state.revision;

    try {
      const [tabs, settings] =
        await Promise.all([
          chrome.tabs.query({
            active: true,
            currentWindow: true,
          }),
          chrome.storage.local.get(
            settingKeys
          ),
        ]);

      if (
        state.disposed ||
        revision !== state.revision
      ) {
        return;
      }

      adoptTab(tabs[0]);
      state.settings = settings;
      updateControls();

      if (!state.page) {
        setState(
          'neutral',
          'Page not scanned',
          'Dadblock scans supported HTTP and HTTPS pages.',
        );

        return;
      }

      if (
        isIgnored(
          state.tab.url,
          state.page.hostname,
          settings.ignoreRules,
        )
      ) {
        clearPendingScan();
        updateControls();

        setState(
          'neutral',
          'Scanning paused here',
          'You told Dad to skip ' + (state.page ? state.page.hostname : 'this site') + '. Open Settings, find "Look the other way", and remove it to scan here again.',
        );

        return;
      }

      if (
        state.tab.status === 'loading'
      ) {
        setState(
          'neutral',
          'Page is loading',
          'Wait for the page to finish loading before scanning.',
        );

        return;
      }

      const tabId =
        state.tab.id;

      const url =
        state.tab.url;

      const status = await request({
        action: 'getStatus',
        tabId,
      });

      if (
        state.disposed ||
        revision !== state.revision
      ) {
        return;
      }

      if (
        state.tab?.id !== tabId ||
        state.tab?.url !== url
      ) {
        return;
      }

      const mode =
        selectedMode(settings);

      const current =
        status &&
        status.url === url &&
        Number.isFinite(status.timestamp) &&
        status.timestamp >=
          state.minimumTimestamp &&
        status.result &&
        resultMatchesMode(
          status.result,
          mode
        );

      if (current) {
        clearPendingScan();
        displayResult(status.result);
      } else if (state.pendingScan) {
        showScanning();
      } else {
        setState(
          'neutral',
          !autoScanEnabled(settings)
            ? 'Automatic scanning is off'
            : 'Page not verified',
          'Use "Scan now" to check this page.',
        );
      }

      updateControls();
    } catch {
      if (
        state.disposed ||
        revision !== state.revision
      ) {
        return;
      }

      clearPendingScan();

      setState(
        'neutral',
        'Scan status unavailable',
        'Dadblock could not read the scan status. Try again.',
      );

      updateControls();
    }
  }

  async function activePageTab() {
    const [tab] =
      await chrome.tabs.query({
        active: true,
        currentWindow: true,
      });

    if (
      !tab ||
      !Number.isInteger(tab.id) ||
      !webPage(tab.url)
    ) {
      throw new Error(
        'No supported page'
      );
    }

    return tab;
  }

  async function scanNow(
    clearCache = false
  ) {
    if (
      state.busy ||
      state.pendingScan ||
      state.disposed
    ) {
      return;
    }

    state.busy = true;
    state.revision++;
    updateControls();

    setState(
      'neutral',
      'Preparing scan...',
      'Requesting a scan of the active page.',
      true,
    );

    let intent = null;

    try {
      const tab =
        await activePageTab();

      if (state.disposed) return;

      adoptTab(tab);
      state.minimumTimestamp =
        Date.now();

      intent = {
        tabId: tab.id,
        url: tab.url,
      };

      state.pendingScan = intent;
      updateControls();
      showScanning();

      // An acknowledgement is not a verdict.
      scanTimer = setTimeout(
        () => {
          if (
            state.disposed ||
            state.pendingScan !== intent
          ) {
            return;
          }

          clearPendingScan();

          setState(
            'neutral',
            'Scan timed out',
            'No completed result arrived. This page has not been verified.',
          );

          updateControls();
        },
        75000
      );

      if (clearCache) {
        const cleared =
          await request({
            action: 'clearTabCache',
            tabId: tab.id,
          });

        if (
          state.pendingScan !== intent ||
          state.disposed
        ) {
          return;
        }

        if (
          cleared?.success !== true
        ) {
          throw new Error(
            'Cache clear failed'
          );
        }
      }

      const response =
        await request({
          action: 'manualScan',
          tabId: tab.id,
        });

      if (
        state.pendingScan !== intent ||
        state.disposed
      ) {
        return;
      }

      if (
        response?.success !== true
      ) {
        throw new Error(
          'Scan request failed'
        );
      }

      scheduleRefresh();
    } catch {
      if (
        state.disposed ||
        (
          intent &&
          state.pendingScan !== intent
        )
      ) {
        return;
      }

      clearPendingScan();

      setState(
        'neutral',
        'Scan could not start',
        'The scanner could not be reached. Reload this page and try again.',
      );
    } finally {
      state.busy = false;

      if (!state.disposed) {
        updateControls();
      }
    }
  }

  async function pageAction(
    changeSettings
  ) {
    if (
      state.busy ||
      state.pendingScan ||
      state.disposed
    ) {
      return;
    }

    state.busy = true;
    updateControls();

    try {
      const tab =
        await activePageTab();

      const hostname =
        new URL(tab.url).hostname;

      await changeSettings(
        tab,
        hostname
      );

      if (state.disposed) return;

      state.revision++;
      state.minimumTimestamp =
        Date.now();

      setState(
        'neutral',
        'Reloading page...',
        'Applying your site settings.',
      );

      await chrome.tabs.reload(
        tab.id
      );
    } catch {
      if (!state.disposed) {
        setState(
          'neutral',
          'Site settings could not be applied',
          'Try the action again.',
        );
      }
    } finally {
      state.busy = false;

      if (!state.disposed) {
        updateControls();
        scheduleRefresh();
      }
    }
  }

